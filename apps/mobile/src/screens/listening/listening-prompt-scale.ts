// 제시문의 글자 크기를 문장 길이에서 정합니다.
//
// **왜 한 크기로 못 두는가.** 디자인(Figma 53-14231)의 제시문은 `이거 주세요` 같은 짧은
// 구절이고 `display`(34/41)가 그 길이에 맞춰진 크기입니다. 우리 문항은 문장이고, 가장
// 긴 것은 38자입니다 — 같은 크기로 두면 세 줄로 접혀 카드가 120pt 넘게 늘어나고, 그만큼이
// 아래 보기를 화면 밖으로 밀어 **스크롤을 만듭니다.** 학습 화면은 스크롤이 없는 것이
// 설계입니다.
//
// **자동 축소(글자를 상자에 맞춰 줄이기)를 쓰지 않습니다.** Lynx에 그 수단이 있는지
// 확인되지 않았고, 있더라도 크기가 기기마다 달라져 판정할 수 없습니다. 길이에서
// 단계를 고르면 **같은 문항은 어디서나 같은 크기**이고, 그 규칙을 `unit`이 봅니다.

/**
 * 제시문 크기 단계입니다. 세 단계로 끊는 것은 카드 폭(약 336pt)에서 한 줄에 들어가는
 * 한글 글자 수가 대략 10 · 12 · 15로 갈리기 때문입니다 — 그 경계에서 줄 수가 바뀝니다.
 */
export type ListeningPromptScale = "l" | "m" | "s";

/** `l`이 한 줄에 담는 한글 글자 수의 어림값입니다(카드 폭 336pt · 34px 기준). */
const largeLineLength = 10;

/** `m`(28px)이 두 줄에 담는 어림값입니다. */
const mediumCapacity = 24;

/**
 * 문장 길이에서 크기 단계를 고릅니다. 공백도 한 자로 셉니다 — 줄을 차지하는 것은
 * 같습니다.
 *
 * 경계는 **두 줄 안에 들어가는가**입니다. `l`은 한 줄, `m`은 두 줄까지 받고, 그보다
 * 길면 `s`로 내려 세 줄에서 멈춥니다.
 */
export function listeningPromptScale(text: string): ListeningPromptScale {
  const length = text.length;
  if (length <= largeLineLength) {
    return "l";
  }
  if (length <= mediumCapacity) {
    return "m";
  }
  return "s";
}
