// 손글씨 탐침 화면의 값을 소유합니다 — 표면 크기 · 획 굵기 · 안내 글자 · 팽창 반경입니다.
//
// 좌표를 SVG 문서로 바꾸는 함수는 `lib/stroke-svg.ts`로 올라갔습니다 — 그리기 표면을 쓰기
// 학습도 쓰게 되어 이 탐침만의 것이 아니게 됐습니다. 여기 남은 수는 이 탐침 바깥에 소비자가
// 없습니다. 쓰기 학습의 수는 `lib/writing-canvas.ts`가 따로 집니다.

/**
 * 그리기 표면의 고정 크기입니다. `viewBox`·CSS 박스와 같은 수를 씁니다.
 *
 * ⚠ 같은 수가 `handwriting-probe-screen.css`의 `-surface`에도 있습니다 — 시각 값을 CSS에
 * 두는 규약 때문에 한 자리로 합칠 수 없습니다. 둘이 갈리면 좌표 변환이 항등이 아니게 되어
 * 획이 손가락과 다른 자리에 그려집니다. `HandwritingProbeScreen.ui.test.tsx`의 DS13이
 * 둘을 묶습니다.
 */
export const probeSurfaceSize = { width: 300, height: 300 } as const;

/**
 * 그리기 표면의 획 굵기입니다.
 *
 * ⟨2026-09-28⟩ **6에서 14로 올렸습니다.** 두 가지가 함께 걸립니다.
 *
 * 눈으로는 얇았습니다 — 안내 글자가 두꺼운 면인데 그 위에 실선 하나가 지나가는 모양이라
 * 「따라 썼다」로 안 보입니다.
 *
 * 그리고 **지표가 구조적으로 눌립니다.** `덮음`은 그린 것을 팽창시켜 안내를 얼마나
 * 채웠나를 보는데, 펜이 안내보다 얇으면 팽창으로 메울 수 있는 몫에 한계가 있습니다 —
 * 완벽하게 따라 그려도 상한이 1에 못 미칩니다. 14는 이 크기(240px)에서 안내 획이 실제로
 * 차지하는 두께(약 13pt, 기기에서 잼)에 맞춘 수입니다.
 */
export const probeStrokeWidth = 14;

// ---------------------------------------------------------------- 따라 쓰기 견주기

/**
 * 탐침이 쓰는 안내 글자입니다. 디자인이 고른 음절과 같습니다(Figma 79-6374).
 *
 * 한 글자입니다 — 지표가 「안내를 얼마나 덮었나」라, 글자가 둘이면 하나만 잘 쓰고
 * 하나를 비워도 비가 반쯤 나옵니다. 그 뭉개짐을 탐침 단계에서 만들지 않습니다.
 */
export const probeTraceGlyph = "주";

/**
 * 안내 글자 크기입니다. 표면 300의 0.8입니다 — 꽉 채우면 획이 판 가장자리에 닿아
 * 사람이 그 위를 덧그릴 자리가 없고, 너무 작으면 잉크 픽셀이 적어 비가 몇 픽셀에
 * 흔들립니다.
 */
export const probeTraceFontSize = probeSurfaceSize.width * 0.8;

/**
 * 팽창 반경(표면 point)입니다. 「얼마나 빗나가도 따라 쓴 것으로 보는가」입니다.
 *
 * ⟨2026-09-28⟩ **획 두께와 떼어 놨습니다.** 처음에는 같은 수로 뒀는데(「펜 하나 굵기만큼
 * 빗나가도 봐준다」가 이해되는 출발선이라서), 획을 14로 올리면서 이 값도 따라 오르면
 * 팽창이 28pt 폭이 되어 **`머무름`이 거의 무조건 1에 붙습니다.** 봐주는 정도와 펜 굵기는
 * 서로 다른 것을 정하므로 각자 둡니다.
 *
 * ⚠ **이 값도 문턱값도 아직 근거가 없습니다.** 기기에서 사람이 실제로 써 보며 잡아야
 * 하고, 그 전까지 이 수를 「정해진 것」으로 읽지 않습니다.
 */
export const probeTraceTolerance = 6;
